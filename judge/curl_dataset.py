"""Turns an evaluation dataset into a bash script of plain curl commands, one per request.

    uv run python curl_dataset.py datasets/01_tricks.json > .local/curl/01_tricks.sh
    bash .local/curl/01_tricks.sh http://127.0.0.1:8000

Every report becomes one `curl -X POST .../reports` with the PRD Appendix A body, and every dispute
one `curl -X POST .../challenges`, in the dataset's order. The script checks each reply's status
against what the dataset expects (201, or 400 for junk, or 429 for spam) and says which ones
differ. The dataset's times are moved so that its anchor becomes "now" at generation, keeping
each time's own offset and the gaps between them. The script is pure ASCII (non-English notes are
JSON \\u escapes), with Unix line endings, so it runs the same anywhere bash does.

Owner: B. Filled in by: B9.
"""

from __future__ import annotations

import json
import shlex
import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from score_dataset import shift

HEADER = """#!/usr/bin/env bash
# Generated by judge/curl_dataset.py from @NAME@: @REPORTS@ reports and @CHALLENGES@ disputes,
# one plain curl command each, in this order. Usage: bash this-file.sh [BASE_URL]
BASE=${1:-http://127.0.0.1:8000}
sent=0
bad=0
expect() {  # reply status, statuses the dataset allows, what was sent
  sent=$((sent + 1))
  if [ -n "${STATUS_LOG:-}" ]; then printf '%s\\t%s\\n' "$1" "$3" >> "$STATUS_LOG"; fi
  case " $2 " in
    *" $1 "*) printf '.' ;;
    *) bad=$((bad + 1)); printf '\\n!! %s: got %s, wanted %s\\n' "$3" "$1" "$2" ;;
  esac
  if [ $((sent % 50)) -eq 0 ]; then printf '\\n'; fi
}
"""

FOOTER = """printf '\\n%s requests sent, %s with an unexpected status\\n' "$sent" "$bad"
[ "$bad" -eq 0 ]
"""


def _line(path: str, body: dict[str, Any], allowed: list[int], what: str) -> str:
    payload = shlex.quote(json.dumps(body, ensure_ascii=True))
    allowed_text = " ".join(str(code) for code in allowed)
    return (
        f"code=$(curl -s -o /dev/null -w '%{{http_code}}' -X POST \"$BASE{path}\""
        f" -H 'content-type: application/json' -d {payload});"
        f' expect "$code" "{allowed_text}" {shlex.quote(what)}\n'
    )


def generate(doc: dict[str, Any], delta: timedelta) -> str:
    """The bash script for a dataset document, with every time moved forward by delta."""
    name = doc.get("_about", "a dataset")
    script = (
        HEADER.replace("@NAME@", str(name).replace("\n", " "))
        .replace("@REPORTS@", str(len(doc["reports"])))
        .replace("@CHALLENGES@", str(len(doc["challenges"])))
    )
    for body in doc["reports"]:
        allowed = doc["expect_status"].get(body["report_id"], [201])
        script += _line("/reports", shift(body, delta), allowed, str(body["report_id"]))
    for n, (challenge, allowed) in enumerate(
        zip(doc["challenges"], doc["challenge_status"], strict=True), start=1
    ):
        script += _line("/challenges", challenge, allowed, f"dispute {n}")
    return script + FOOTER


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        sys.stderr.write("usage: curl_dataset.py DATASET.json > load.sh\n")
        return 2
    doc = json.loads(Path(args[0]).read_text(encoding="utf-8"))
    anchor = datetime.fromisoformat(doc["_anchor"])
    delta = datetime.now(UTC).replace(second=0, microsecond=0) - anchor
    # Bytes, not text: on Windows text mode would turn every newline into CRLF and break bash.
    sys.stdout.buffer.write(generate(doc, delta).encode("ascii"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
